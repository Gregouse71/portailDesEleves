				<br><br>
				Le midi, vous disposerez a priori d’au moins une heure pour manger, parfois deux, ce qui vous laisse le temps de profiter du restaurant universitaire, de rentrer à la Maison des Mines pour vous cuisiner vous-même quelque chose ou encore de vous acheter un repas chez un des nombreux commerçants du quartier. Ensuite, libre à vous de venir manger chez vous ou, dans le jardin de l’École quand il fait beau, ou au foyer entre deux parties de baby foot.
				<br><br>
				Le soir, de nombreuses activités ont lieu toute la semaine au sous-sol de la résidence. Une fois par semaine, vous pourrez venir y pratiquer, par exemple, la zumba, ou encore prendre part au club Rock. D’autres rendez-vous hebdomadaires vous attendent également une fois rentré comme la rédaction du Vendôme, le journal de l’École, tous les lundis soirs, ou les répétitions de la fanfare.
				<br><br>
				Une seule règle demeure : faites vous plaisir, l'école et les associations sont là pour ça !
